"""Regenerate the SM70 GGML codebooks from the owned integer-bit authority."""

import argparse
from pathlib import Path
import runpy


def render(root):
    source = runpy.run_path(str(root / "src/tensorfold/families/qwen4_exp/gguf_tables.py"))
    result = ["// Generated by tools/generate_gguf_decode_tables.py; do not edit.",
              "// GGML MIT codebook provenance is retained in gguf_tables.py and THIRD_PARTY_NOTICES.md.",
              "#pragma once", "#include <cstdint>", ""]
    result.append("#define TF_GGUF_IQ4NL_VALUES " + ", ".join(map(str, source["KVALUES_IQ4NL"])))
    result.append("")
    for name, kind in (("KSIGNS_IQ2XS", "uint8_t"),
                       ("IQ2S_GRID", "uint64_t"), ("IQ3XXS_GRID", "uint32_t"),
                       ("IQ3S_GRID", "uint32_t"), ("KVALUES_IQ4NL", "int8_t")):
        values = source[name]
        result.append(f"static const __device__ {kind} tf_{name.lower()}[{len(values)}] = {{")
        suffix = "ULL" if kind == "uint64_t" else "U" if kind == "uint32_t" else ""
        for start in range(0, len(values), 8):
            result.append("    " + ", ".join(str(value) + suffix for value in values[start:start + 8]) + ",")
        result.extend(["};", ""])
    return "\n".join(result)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    target = root / "src/tensorfold/cuda/sm70/gguf_decode_tables.cuh"
    expected = render(root)
    if args.check:
        if not target.exists() or target.read_text() != expected:
            raise SystemExit("GGUF decoder tables need regeneration")
    else:
        target.write_text(expected)


if __name__ == "__main__":
    main()
