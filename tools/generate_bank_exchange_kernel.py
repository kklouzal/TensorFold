"""Generate the C-exchange kernel from the unchanged owned G byte-loop source."""

from __future__ import annotations

import hashlib
from pathlib import Path

from tensorfold.cleanup import raise_failures

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/tensorfold/cuda/nvfp4/bank_cpu.cpp"
OUTPUT = SOURCE.with_name("bank_exchange_kernel.h")


def source_bytes(path):
    errors = [None]
    stream = path.open("rb")
    try:
        raw = stream.read((1 << 20) + 1)
    except BaseException as primary:
        try:
            stream.close()
        except BaseException as cleanup:  # noqa: BLE001 - preserve owned source read/close roots.
            errors[0] = cleanup
            raise_failures(primary, errors)
        raise
    stream.close()
    if len(raw) > 1 << 20:
        raise ValueError("owned bank source exceeds one MiB")
    return raw


def generate(raw):
    text = raw.decode()
    start, end = "// Copy logical words", "static void pack("
    warm, stop = "    py::gil_scoped_release release;\n", "\n}\n\nPYBIND11_MODULE"
    if any(text.count(marker) != 1 for marker in (start, end, warm, stop)):
        raise ValueError("canonical G kernel extraction markers differ")
    helpers = text[text.index(start):text.index(end)]
    loop = text[text.index(warm) + len(warm):text.index(stop)]
    return ("// Generated by tools/generate_bank_exchange_kernel.py; do not edit.\n"
            f"// Canonical G source SHA256 {hashlib.sha256(raw).hexdigest()}\n"
            "#pragma once\n#include <cstdint>\n#include <cstring>\n"
            "namespace a4_bank_kernel {\nusing U = std::uint64_t;\n" + helpers
            + "static void copy_bank(const std::uint8_t* code_data, const std::uint8_t* sf_data,\n"
            "                      std::uint8_t* up_data, std::uint8_t* down_data, const std::int64_t* local,\n"
            "                      U count, U width, U dims, U words, U sf, U blob, U up_stride, U down_stride) {\n"
            + loop + "\n}\n} // namespace a4_bank_kernel\n").encode()


def write_output(path, data):
    errors = [None]
    stream = path.open("wb")
    try:
        if stream.write(data) != len(data):
            raise OSError("short generated-header write")
    except BaseException as primary:
        try:
            stream.close()
        except BaseException as cleanup:  # noqa: BLE001 - preserve partial output and write/close roots.
            errors[0] = cleanup
            raise_failures(primary, errors)
        raise
    stream.close()


if __name__ == "__main__":
    write_output(OUTPUT, generate(source_bytes(SOURCE)))
