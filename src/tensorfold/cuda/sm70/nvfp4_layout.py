"""Single source for the owned software-NVFP4 tile/numerical interface."""

PROFILE = "nvfp4-e2m1-e4m3-fp16-fp32-v1"
ROWS, OUTPUTS, INPUTS = 32, 64, 256
LINEAR_REFERENCE = "sm70-nvfp4-torch-tiled-reference-v1"
LINEAR_WMMA = "sm70-nvfp4-wmma-m32-n64-k256-v1"
LINEAR_FAMILIES = (LINEAR_REFERENCE, LINEAR_WMMA)
EXPERT_REFERENCE = "sm70-nvfp4-cpu-grouped-reference-v1"
EXPERT_DEVICE = "sm70-nvfp4-device-grouped-wmma-v1"
EXPERT_FAMILIES = (EXPERT_REFERENCE, EXPERT_DEVICE)
EXPERT_FIELDS = ("DATA", "SCALES", "GLOBAL", "ROWS", "COLUMNS", "KIND", "DATA_BYTES", "SCALE_ELEMENTS")
EXPERT_WORDS, EXPERT_ABI = len(EXPERT_FIELDS), 1


def expert_shape(rows, slots, experts):
    if any(type(n) is not int or n <= 0 for n in (rows, slots, experts)):
        raise ValueError("device expert plan requires positive integer row/slot/expert bounds")
    pairs = rows * slots
    tiles = experts + (pairs + ROWS - 1) // ROWS
    if pairs > 2**31 - 1 or tiles > 2**31 - 1:
        raise ValueError("device expert plan exceeds its checked INT32 work domain")
    return pairs, tiles


def expert_workspace_bytes(rows, slots, experts, width):
    pairs, tiles = expert_shape(rows, slots, experts)
    if type(width) is not int or width <= 0:
        raise ValueError("device expert width must be a positive integer")
    return 4 * (experts + experts + 1 + pairs + 2 * tiles + 1) + 2 * pairs * width


def render_header():
    return ("// Generated by python -m tensorfold.cuda.sm70.nvfp4_layout; do not edit.\n"
            "#pragma once\n"
            f'#define TF_SM70_NVFP4_PROFILE "{PROFILE}"\n'
            f"#define TF_SM70_NVFP4_ROWS {ROWS}\n"
            f"#define TF_SM70_NVFP4_OUTPUTS {OUTPUTS}\n"
            f"#define TF_SM70_NVFP4_INPUTS {INPUTS}\n"
            f"#define TF_SM70_NVFP4_EXPERT_WORDS {EXPERT_WORDS}\n"
            f"#define TF_SM70_NVFP4_EXPERT_ABI {EXPERT_ABI}\n"
            "enum TfNvfp4Field { " + ", ".join(f"TF_NV_{name} = {i}" for i, name in enumerate(EXPERT_FIELDS)) + " };\n")


if __name__ == "__main__":
    import argparse
    from pathlib import Path

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    target = Path(__file__).with_suffix(".cuh")
    expected = render_header()
    if options.check:
        if target.read_text() != expected:
            raise SystemExit("SM70 NVFP4 generated interface differs; regenerate its owned header")
    else:
        target.write_text(expected)
