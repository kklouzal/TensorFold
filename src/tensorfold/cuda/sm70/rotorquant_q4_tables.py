"""Generate native Q4 tables from rotorquant_ref and rotorquant_compact authorities."""
from __future__ import annotations

import argparse
from pathlib import Path
import struct

from tensorfold.families.qwen4_exp.cuda import rotorquant_ref as ref
from tensorfold.cuda.sm70 import rotorquant_compact as compact


def _bits(values):
    return ", ".join(f"0x{struct.unpack('<I', struct.pack('<f', value))[0]:08x}u" for value in values)


def render():
    """Return the exact declared compiler input; no runtime/device state."""
    return f'''// Generated by rotorquant_q4_tables.py from rotorquant_ref.py; do not edit.
// {ref.descriptor(4, "signed-iso128").codec_id}
#pragma once
#include <cstdint>

namespace tf_rq4 {{
static __device__ __constant__ uint32_t centroid_bits[16] = {{{_bits(ref.CENTROIDS_4)}}};
static __device__ __constant__ uint32_t threshold_bits[15] = {{{_bits(ref.THRESHOLDS_4)}}};
static __device__ __constant__ uint32_t planar_cos_bits[4] = {{{_bits(ref.PLANAR_COS)}}};
static __device__ __constant__ uint32_t planar_sin_bits[4] = {{{_bits(ref.PLANAR_SIN)}}};
constexpr uint64_t sign_pair_mask = 0x{ref.SIGN_PAIR_NEGATIVE_MASK:016x}ull;
constexpr uint32_t wide_cos_bits = {_bits((ref.WIDE_GIVENS_COS,))};
constexpr uint32_t wide_sin_bits = {_bits((ref.WIDE_GIVENS_SIN,))};
// {compact.descriptor().codec_id}
static __device__ __constant__ uint32_t compact_centroid_bits[16] = {{{_bits(compact.CENTROIDS)}}};
static __device__ __constant__ uint32_t compact_cos_bits[64] = {{{_bits(compact.COS)}}};
static __device__ __constant__ uint32_t compact_sin_bits[64] = {{{_bits(compact.SIN)}}};
// {compact.descriptor(compact.ISO_CODEC).codec_id}
static __device__ __constant__ uint32_t compact_qw_bits[32] = {{{_bits(compact.QW)}}};
static __device__ __constant__ uint32_t compact_qx_bits[32] = {{{_bits(compact.QX)}}};
static __device__ __constant__ uint32_t compact_qy_bits[32] = {{{_bits(compact.QY)}}};
static __device__ __constant__ uint32_t compact_qz_bits[32] = {{{_bits(compact.QZ)}}};
}}  // namespace tf_rq4
'''


def verify(path=None):
    path = Path(path) if path is not None else Path(__file__).with_suffix(".cuh")
    if path.read_text() != render():
        raise ValueError("SM70 RotorQuant Q4 generated tables differ from the canonical format authority")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path(__file__).with_suffix(".cuh"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        verify(args.output)
    else:
        args.output.write_text(render())


if __name__ == "__main__":
    main()
