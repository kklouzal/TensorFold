"""Authoritative private CPU/CUDA row-descriptor schema for owner attention."""

import hashlib
import json

ABI_VERSION = 1
WORD_BYTES = 8
FIELDS = (
    "K_DATA", "V_DATA", "K_METADATA", "V_METADATA", "PAGE_OFFSETS", "GENERATIONS", "STATUS",
    "POSITION", "LIVE_ROWS", "EXPECTED_SLOT", "EXPECTED_OWNER", "LOGICAL_CAPACITY", "PHYSICAL_ROWS",
    "PAGE_COUNT", "ROW_OFFSET", "INDEXER_OWNER",
)
WORDS = len(FIELDS)
BYTES = WORDS * WORD_BYTES
SCHEMA_ID = "tf-sm70-paged-" + hashlib.sha256(json.dumps(
    {"abi": ABI_VERSION, "word_bytes": WORD_BYTES, "fields": FIELDS},
    sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def render_header():
    """Deterministic enum shared by bindings and device pointer interpretation."""

    members = "\n".join(f"    {name} = {index}," for index, name in enumerate(FIELDS))
    return ("// Generated by tools/generate_sm70_paged_descriptor.py; edit the Python schema.\n"
            "#pragma once\n#include <cstdint>\n\nnamespace tf_sm70_paged {\n"
            f"constexpr int ABI_VERSION = {ABI_VERSION};\nconstexpr int WORD_BYTES = {WORD_BYTES};\n"
            f'constexpr const char* SCHEMA_ID = "{SCHEMA_ID}";\n'
            "static_assert(sizeof(int64_t) == WORD_BYTES);\n"
            "static_assert(sizeof(uintptr_t) == WORD_BYTES);\n"
            "enum Word : int {\n" + members + f"\n    WORD_COUNT = {WORDS}\n" + "};\n"
            "}  // namespace tf_sm70_paged\n")
